"""
Pydantic schemas for the Deep Research Agent API.

Defines request validation and response structures for
research sessions and human-review decisions.
"""

from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, Field, ConfigDict


# ---------------------------------------------------------
# RESEARCH REQUESTS
# ---------------------------------------------------------

class ResearchRequest(BaseModel):
    """Request to start a new research session."""

    question: str = Field(
        min_length=1,
        max_length=2000,
        description="The research question to investigate.",
    )

    require_initial_plan_approval: bool = True
    require_initial_research_approval: bool = True
    require_adaptive_research_approval: bool = True
    require_final_report_approval: bool = True

    max_research_rounds: int = Field(
        default=3,
        ge=1,
        le=10,
    )

    max_total_research_questions: int = Field(
        default=10,
        ge=1,
        le=50,
    )


# ---------------------------------------------------------
# HUMAN REVIEW
# ---------------------------------------------------------

class ResearchQuestionRevision(BaseModel):
    """Replacement details for a proposed research question."""

    question_number: int = Field(ge=1)

    question: str = Field(
        min_length=1,
        max_length=2000,
    )

    search_queries: list[str] = Field(
        default_factory=list,
        max_length=10,
    )


class ReviewDecisionRequest(BaseModel):
    """
    Human decision submitted to a pending review.

    The allowed action depends on the review type.
    """

    action: Literal[
        "approve",
        "revise",
        "reject",
        "research_more",
    ]

    question_number: int | None = Field(
        default=None,
        ge=1,
    )

    question: str | None = Field(
        default=None,
        max_length=2000,
    )

    search_queries: list[str] | None = Field(
        default=None,
        max_length=10,
    )

    reason: str | None = Field(
        default=None,
        max_length=2000,
    )


# ---------------------------------------------------------
# RESEARCH SESSION RESPONSES
# ---------------------------------------------------------

class ResearchJobSummary(BaseModel):
    """Current durable job state shown with a research session."""

    id: str
    status: Literal[
        "queued",
        "running",
        "retry_wait",
        "awaiting_review",
        "completed",
        "failed",
        "cancelled",
        "paused",
    ]
    attempt_count: int
    max_attempts: int
    cancel_requested: bool = False
    pause_requested: bool = False
    last_error: str | None = None


class ResearchSessionSummary(BaseModel):
    """Compact representation of a research session."""

    id: str
    question: str

    status: Literal[
        "created",
        "running",
        "waiting_for_review",
        "completed",
        "failed",
        "cancelled",
        "paused",
    ]

    created_at: datetime | None = None
    updated_at: datetime | None = None
    job: "ResearchJobSummary | None" = None


class ResearchSessionResponse(ResearchSessionSummary):
    """Detailed research session response."""

    research_state: dict[str, Any] | None = None
    final_report: dict[str, Any] | None = None
    error_message: str | None = None
    completed_at: datetime | None = None


class ResearchSessionListResponse(BaseModel):
    """Response containing recent research sessions."""

    sessions: list[ResearchSessionSummary]


# ---------------------------------------------------------
# REVIEW RESPONSES
# ---------------------------------------------------------

class PendingReviewResponse(BaseModel):
    """Human-review request waiting for a decision."""

    session_id: str

    review: dict[str, Any] = Field(
        description="Review payload generated by the research graph.",
    )


class ReviewSubmissionResponse(BaseModel):
    """Result of submitting a review decision."""

    session_id: str

    status: Literal[
        "running",
        "waiting_for_review",
        "completed",
        "failed",
        "cancelled",
        "paused",
    ]

    message: str
    job_id: str | None = None
    job_status: str | None = None
    attempt_count: int | None = None
    max_attempts: int | None = None
    cancel_requested: bool = False
    pause_requested: bool = False
    last_error: str | None = None


# ---------------------------------------------------------
# GENERAL API RESPONSES
# ---------------------------------------------------------

class ResearchCreatedResponse(BaseModel):
    """Response returned after starting research."""

    session_id: str
    status: Literal["created", "running"]
    message: str
    job_id: str | None = None


class HealthResponse(BaseModel):
    """API health status."""

    status: Literal["ok"]
    service: str = "deep-research-agent"


# ---------------------------------------------------------
# OBSERVABILITY SCHEMAS
# ---------------------------------------------------------

class ObservabilityEventResponse(BaseModel):
    """Structured observability event representation."""

    id: int
    session_id: str | None = None
    event_type: str
    node_name: str | None = None
    log_level: str
    message: str
    duration_ms: float | None = None
    details: dict[str, Any] = Field(default_factory=dict)
    created_at: datetime


class ObservabilityEventsListResponse(BaseModel):
    """List of observability events."""

    events: list[ObservabilityEventResponse]


class SessionDeletedResponse(BaseModel):
    """Response returned when a session is deleted."""

    deleted: bool
    session_id: str


# ---------------------------------------------------------
# SHARED MODEL CONFIGURATION
# ---------------------------------------------------------

class APIModel(BaseModel):
    """Base class for future API models requiring strict extras."""

    model_config = ConfigDict(
        extra="forbid",
    )
